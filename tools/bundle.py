"""Bundle src/AssetKit into one script you can paste into the Studio command bar.

Usage: python3 tools/bundle.py  ->  build/BuildAssetShowcase.lua
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "src" / "AssetKit"
OUT = ROOT / "build" / "BuildAssetShowcase.lua"

REQ = re.compile(r"require\((script(?:\.Parent)*(?:\.\w+)+)\)")


def module_name(path: pathlib.Path) -> str:
    rel = path.relative_to(SRC).with_suffix("")
    return "AssetKit" if rel.name == "init" else rel.name


def main() -> None:
    files = sorted(SRC.rglob("*.luau"))
    names = {module_name(f) for f in files}
    chunks = []
    for f in files:
        name = module_name(f)
        body = f.read_text()

        def repl(m: re.Match) -> str:
            target = m.group(1).split(".")[-1]
            if target not in names:
                raise SystemExit(f"{f}: unknown require target {target}")
            return f'__require("{target}")'

        body = REQ.sub(repl, body)
        # `export type` is only legal at a chunk's top level, and each module becomes a function here.
        body = re.sub(r"^export type ", "type ", body, flags=re.M)
        chunks.append(f'__modules["{name}"] = function()\n{body}\nend\n')

    header = (
        "-- +1 Hit a Ragdoll: asset showcase builder (generated by tools/bundle.py, do not edit)\n"
        "-- Paste all of this into the Studio command bar (View > Command Bar) and press Enter.\n"
        "local __modules, __cache = {}, {}\n"
        "local function __require(name)\n"
        "\tif __cache[name] == nil then __cache[name] = __modules[name]() end\n"
        "\treturn __cache[name]\n"
        "end\n\n"
    )
    footer = (
        'local ChangeHistoryService = game:GetService("ChangeHistoryService")\n'
        'pcall(function() ChangeHistoryService:SetWaypoint("Before AssetShowcase") end)\n'
        'local AssetKit = __require("AssetKit")\n'
        "AssetKit.buildShowcase()\n"
        'pcall(function() ChangeHistoryService:SetWaypoint("Built AssetShowcase") end)\n'
        'print("[AssetKit] Showcase built: Workspace.AssetShowcase, templates in ServerStorage.AssetKitModels")\n'
    )
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(header + "\n".join(chunks) + "\n" + footer)
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
