"""Bundle src/Template (+ the AssetKit Builder, Palette, Lighting it uses) into one
command-bar script.

Usage: python3 tools/bundle_template.py  ->  build/BuildTemplate.lua
Paste the file into the Studio command bar and press Enter. Re-running replaces
Workspace.Map, StarterGui.HUD, ReplicatedStorage.UITemplates and ReplicatedStorage.UIKit.
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
FILES = [
    *sorted((ROOT / "src" / "Template").glob("*.luau")),
    ROOT / "src" / "AssetKit" / "Builder.luau",
    ROOT / "src" / "AssetKit" / "Palette.luau",
    ROOT / "src" / "AssetKit" / "Lighting.luau",
]
OUT = ROOT / "build" / "BuildTemplate.lua"
REQ = re.compile(r"require\((script(?:\.Parent)*(?:\.\w+)+)\)")


def module_name(path: pathlib.Path) -> str:
    return "Template" if path.stem == "init" else path.stem


def main() -> None:
    names = {module_name(f) for f in FILES}
    chunks = []
    for f in FILES:
        body = f.read_text()

        def repl(m: re.Match) -> str:
            target = m.group(1).split(".")[-1]
            if target not in names:
                raise SystemExit(f"{f}: unknown require target {target}")
            return f'__require("{target}")'

        body = REQ.sub(repl, body)
        body = re.sub(r"^export type ", "type ", body, flags=re.M)
        chunks.append(f'__modules["{module_name(f)}"] = function()\n{body}\nend\n')

    ui_src = (ROOT / "src" / "Template" / "UI.luau").read_text()
    assert "]=====]" not in ui_src
    header = (
        "-- +1 Hit a Ragdoll: map + HUD template builder (generated by tools/bundle_template.py, do not edit)\n"
        "-- Paste all of this into the Studio command bar and press Enter.\n"
        "local __modules, __cache = {}, {}\n"
        "local function __require(name)\n"
        "\tif __cache[name] == nil then __cache[name] = __modules[name]() end\n"
        "\treturn __cache[name]\n"
        "end\n"
        f"local __UI_SOURCE = [=====[{ui_src}]=====]\n\n"
    )
    footer = (
        'local ChangeHistoryService = game:GetService("ChangeHistoryService")\n'
        'pcall(function() ChangeHistoryService:SetWaypoint("Before Template") end)\n'
        '__require("Template").build(__UI_SOURCE)\n'
        'pcall(function() ChangeHistoryService:SetWaypoint("Built Template") end)\n'
        'print("[Template] built: Workspace.Map, StarterGui.HUD, ReplicatedStorage.UITemplates + UIKit")\n'
    )
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(header + "\n".join(chunks) + "\n" + footer)
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
